<h3>Noncompliance with the accessibility regulations


</h3>
<p>The
following items to not comply with the WCAG 2.2 AA success criteria:</p>
<p>

</p>
<p>

</p>


	<ul><li>Some artwork image descriptions are based on the artwork title rather than a fuller description of the image, and some legacy artwork records include text within images without an equivalent text alternative<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#non-text-content">1.1.1 -- Non-text Content</a></p>

	<ul><li>Video content has human-corrected captions but does not have a transcript<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#audio-only-and-video-only-prerecorded">1.2.1 -- Audio-only and Video-only (Prerecorded)</a></p>

	<ul><li>Video content does not have audio descriptions<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#audio-description-prerecorded">1.2.5 Audio-Description (Prerecorded)</a></p>

	<ul><li>Some page content is not contained within a landmark region<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#info-and-relationships">1.3.1 -- Info and Relationships</a></p>

	<ul><li>Keyboard focus indicators around the search button and map controls do not have sufficient contrast<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#non-text-contrast">1.4.11 -- Non-text Contrast</a></p>
	<p><a href="https://www.w3.org/TR/WCAG22/#focus-visible">2.4.7 Focus Visible</a></p>

	<ul><li>There are images of text<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#images-of-text">1.4.5 Images of Text</a></p>

	<ul><li>The interactive map cannot be zoomed in or out using the keyboard, although it can be panned and locations can be selected from a list without a mouse<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#keyboard">2.1.1 -- Keyboard</a></p>

	<ul><li>Not all links are formatted correctly with meaningful hypertext, for example some links display a raw web address instead of a descriptive link name<p></li></ul>
	<p><a href="https://www.w3.org/TR/WCAG22/#link-purpose-in-context">2.4.4 -- Link Purpose (In Context)</a></p>


<p>We
aim to improve our websites accessibility on a regular and continuous
basis. See the section below ('What we're doing to improve
